// Generates src/engine/icons.generated.ts and docs/library.md.
// Sources: Tabler outline icons (clipart), Simple Icons (brand logos) and src/engine/icons.custom.json (drawn by hand).
// To add clipart: add an entry below (or to icons.custom.json) and run `npm run icons`.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const tablerDir = join('node_modules', '@tabler', 'icons', 'icons', 'outline');
const simpleDir = join('node_modules', 'simple-icons', 'icons');

// name in jz-motion -> Tabler icon name, description, tags
const TABLER = {
  user: ['user', 'A single person: end user, customer, developer', ['people']],
  users: ['users', 'A group of people: team, audience, many users', ['people']],
  laptop: ['device-laptop', 'Laptop: developer machine, desktop client', ['device', 'client']],
  phone: ['device-mobile', 'Mobile phone: mobile app, mobile client', ['device', 'client']],
  browser: ['browser', 'Browser window: web app, frontend', ['client', 'app']],
  server: ['server', 'Server rack: backend, API server, host', ['infra']],
  database: ['database', 'Database: SQL/NoSQL store, persistence', ['infra', 'data']],
  cloud: ['cloud', 'Cloud: cloud provider, internet, external service', ['infra']],
  queue: ['stack-2', 'Stacked layers: queue, stack, layered system', ['infra', 'data']],
  api: ['api', 'The letters API: an API or endpoint', ['app']],
  cpu: ['cpu', 'Chip: CPU, compute', ['infra', 'hardware']],
  robot: ['robot', 'Robot: AI agent, bot, automation', ['ai']],
  brain: ['brain', 'Brain: LLM, model, intelligence', ['ai']],
  chatbot: ['message-chatbot', 'Chat bubble with a face: chatbot, assistant', ['ai', 'app']],
  sparkles: ['sparkles', 'Sparkles: AI magic, generation, new feature', ['ai']],
  lock: ['lock', 'Padlock: auth, security, secrets', ['security']],
  file: ['file-text', 'Document: file, prompt, config, JSON', ['data']],
  world: ['world', 'Globe: internet, public web, global', ['infra']],
};

// name in jz-motion -> Simple Icons slug, description
const LOGOS = {
  anthropic: ['anthropic', 'Anthropic logo'],
  claude: ['claude', 'Claude logo (the Anthropic model / app)'],
  google: ['google', 'Google "G" logo'],
  gemini: ['googlegemini', 'Google Gemini logo'],
  deepseek: ['deepseek', 'DeepSeek logo (whale)'],
  qwen: ['qwen', 'Qwen logo (Alibaba)'],
  meta: ['meta', 'Meta logo (Llama models)'],
  mistral: ['mistralai', 'Mistral AI logo'],
  huggingface: ['huggingface', 'Hugging Face logo'],
  ollama: ['ollama', 'Ollama logo (local models)'],
  nvidia: ['nvidia', 'NVIDIA logo'],
  apple: ['apple', 'Apple logo'],
};

const sections = [];

const tabler = {};
for (const [name, [slug, description, tags]] of Object.entries(TABLER)) {
  const svg = readFileSync(join(tablerDir, `${slug}.svg`), 'utf8');
  // Skip Tabler's invisible bounding-box path.
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`no paths in ${slug}`);
  tabler[name] = { description, tags, paths };
}
sections.push(['Clipart', 'From [Tabler Icons](https://tabler.io/icons), MIT.', tabler]);

const logos = {};
for (const [name, [slug, description]] of Object.entries(LOGOS)) {
  const svg = readFileSync(join(simpleDir, `${slug}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`no paths in ${slug}`);
  logos[name] = { description, tags: ['logo'], style: 'logo', paths };
}

const custom = JSON.parse(readFileSync('src/engine/icons.custom.json', 'utf8'));
const isLogo = (d) => d.tags.includes('logo');
const customLogos = Object.fromEntries(Object.entries(custom).filter(([, d]) => isLogo(d)));
const customClipart = Object.fromEntries(Object.entries(custom).filter(([, d]) => !isLogo(d)));
sections.push(['Hardware and hand-drawn clipart', 'Drawn for jz-motion in `src/engine/icons.custom.json`.', customClipart]);
sections.push([
  'Logos',
  'Brand logos are drawn as neon outlines. From [Simple Icons](https://simpleicons.org) (CC0); `openai` is a simplified hand-drawn version. Logos are trademarks of their owners: use them to refer to the company or product, not to suggest endorsement.',
  { ...logos, ...customLogos },
]);

const all = Object.assign({}, ...sections.map(([, , icons]) => icons));
const header = '// Generated by scripts/import-icons.mjs. Do not edit by hand.\n'
  + '// Clipart from Tabler Icons (https://tabler.io/icons), MIT License, Copyright (c) 2020-2024 Paweł Kuna.\n'
  + '// Logos from Simple Icons (https://simpleicons.org), CC0; logos are trademarks of their owners.\n';
writeFileSync(
  'src/engine/icons.generated.ts',
  `${header}import type { IconDef } from './library';\n\nexport const generatedIcons: Record<string, IconDef> = ${JSON.stringify(all, null, 2)};\n`,
);

const md = sections.map(([title, note, icons]) => {
  const rows = Object.entries(icons)
    .map(([name, d]) => `| \`${name}\` | ${d.description} | ${d.tags.join(', ')} |`)
    .join('\n');
  return `## ${title}\n\n${note}\n\n| Name | What it shows / use it for | Tags |\n|---|---|---|\n${rows}\n`;
});
writeFileSync(
  'docs/library.md',
  `<!-- Generated by scripts/import-icons.mjs. Do not edit by hand. -->\n# Element library\n\nIcons usable as \`{ "type": "icon", "icon": "<name>" }\`. Every icon is drawn stroke by stroke on a 24×24 grid and scaled to \`size\`.\n\n${md.join('\n')}`,
);
console.log(`wrote ${Object.keys(all).length} icons`);
